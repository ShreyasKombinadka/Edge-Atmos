#include "BITMAP.h"

// ASCII charecters bitmap
//--------------------------------------------------------------
// Letters uppercase
uint16_t A[8] = {0x1C, 0x22, 0x22, 0x3E, 0x22, 0x22, 0x22, 0x00};
uint16_t E[16] = {0xFFE, 0xFFE, 0xE06, 0xC00, 0xC00, 0xFFE, 0xFFE, 0xC00, 0xC00, 0xE06, 0xFFE, 0xFFE, 0x00, 0x00, 0x00, 0x00};
// Letters lowercase
uint16_t d[12] = {0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x1F8, 0x218, 0x218, 0x218, 0x1F6, 0x00};
uint16_t e[8] = {0x3E, 0x22, 0x22, 0x3E, 0x20, 0x22, 0x3E, 0x00};
uint16_t g[8] = {0x3E, 0x22, 0x22, 0x3E, 0x02, 0x22, 0x3E, 0x00};
uint16_t m[8] = {0x00, 0x00, 0x3E, 0x2A, 0x2A, 0x2A, 0x2A, 0x00};
uint16_t o[8] = {0x00, 0x00, 0x3E, 0x22, 0x22, 0x22, 0x3E, 0x00};
uint16_t s[8] = {0x00, 0x00, 0x3E, 0x20, 0x3E, 0x02, 0x3E, 0x00};
uint16_t t[8] = {0x08, 0x08, 0x08, 0x3C, 0x08, 0x08, 0x0E, 0x00};
uint16_t *bitmap_char(uint8_t CHAR) // Charecter bitmap
{
    switch (CHAR)
    {
        // Uppercase letters
    case ('A'):
        return A;
    case ('E'):
        return E;

        // Lowercase letters
    case ('d'):
        return d;
    case ('e'):
        return e;
    case ('g'):
        return g;
    case ('m'):
        return m;
    case ('o'):
        return o;
    case ('s'):
        return s;
    case ('t'):
        return t;

    default:
        return 0;
    }
}