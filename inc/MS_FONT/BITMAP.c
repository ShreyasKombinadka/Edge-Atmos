#include "BITMAP.h"

// Letters bitmap
//--------------------------------------------------------------
// Uppercase
uint8_t A[8] = {0x1C, 0x22, 0x22, 0x3E, 0x22, 0x22, 0x22, 0x00};
uint8_t B[8] = {0x3C, 0x22, 0x22, 0x3C, 0x22, 0x22, 0x3C, 0x00};
uint8_t C[8] = {0x1E, 0x20, 0x20, 0x20, 0x20, 0x20, 0x1E, 0x00};
uint8_t E[8] = {0x3E, 0x20, 0x20, 0x3E, 0x20, 0x20, 0x3E, 0x00};
// Lowercase
uint8_t d[8] = {0x04, 0x04, 0x04, 0x3C, 0x24, 0x24, 0x3E, 0x00};
uint8_t e[8] = {0x3E, 0x22, 0x22, 0x3E, 0x20, 0x22, 0x3E, 0x00};
uint8_t g[8] = {0x3E, 0x22, 0x22, 0x3E, 0x02, 0x22, 0x3E, 0x00};
uint8_t m[8] = {0x00, 0x00, 0x3E, 0x2A, 0x2A, 0x2A, 0x2A, 0x00};
uint8_t o[8] = {0x00, 0x00, 0x3E, 0x22, 0x22, 0x22, 0x3E, 0x00};
uint8_t s[8] = {0x00, 0x00, 0x3E, 0x20, 0x3E, 0x02, 0x3E, 0x00};
uint8_t t[8] = {0x08, 0x08, 0x08, 0x3C, 0x08, 0x08, 0x0E, 0x00};
uint8_t *bitmap_letter(uint8_t LETTER) // Letters bitmap
{
    switch (LETTER)
    {
        // Uppercase
    case ('A'):
        return A;
    case ('B'):
        return B;
    case ('C'):
        return C;
    case ('E'):
        return E;

        // Lowercase
    case ('d'):
        return d;
    case ('e'):
        return e;
    case ('g'):
        return g;
    case ('m'):
        return m;
    case ('o'):
        return o;
    case ('s'):
        return s;
    case ('t'):
        return t;
    }
}